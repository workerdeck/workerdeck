#!/usr/bin/env node
// Regenerates the engine-mark vector drawables from `packages/ui`'s `EngineIcon.tsx`, the same table the iOS
// imagesets come from. Run from the repo root: `node apps/android/scripts/gen-engine-marks.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const src = readFileSync(join(root, 'packages/ui/src/components/agent/EngineIcon.tsx'), 'utf8')

const table = src.slice(src.indexOf('const PATHS'), src.indexOf('\n}\n', src.indexOf('const PATHS')))
const marks = [...table.matchAll(/(\w+): \{\s*title: '([^']+)',\s*d: '([^']+)',/g)].map(([, key, title, d]) => ({ key, title, d }))
if (marks.length === 0) {
  throw new Error('no marks parsed - did PATHS change shape?')
}

const drawables = join(root, 'apps/android/app/src/main/res/drawable')
mkdirSync(drawables, { recursive: true })
for (const { key, title, d } of marks) {
  const name = `engine_${key}.xml`
  writeFileSync(
    join(drawables, name),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- ${title} mark, generated by apps/android/scripts/gen-engine-marks.mjs; tinted where drawn. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        android:pathData="${d}" />
</vector>
`,
  )
  console.log(name)
}
